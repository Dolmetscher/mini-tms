import re

from . import tags

_WORD_RE = re.compile(r"[0-9A-Za-zА-Яа-яЁё]+(?:[-'][0-9A-Za-zА-Яа-яЁё]+)*")
# Языки без пробелов (CJK): хирагана/катакана, китайские идеограммы
# (вкл. Extension A и совместимость), корейский хангыль, полуширинная катакана.
_CJK_RE = re.compile(
    "[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff"
    "\uac00-\ud7af\uff66-\uff9f]"
)


def count_words(text: str) -> int:
    """Правило подсчета слов MVP: слова без служебных тегов, по регулярному выражению.

    Токены-теги (<x id="1"/>, <g id="2"></g>) словами не считаются.
    Для языков без пробелов (китайский, японский, корейский) каждая идеограмма/
    слог считается отдельным словом — стандартная упрощенная практика подсчета
    объема для CJK (точный подсчет требует сегментации; упрощение задокументировано).
    """
    plain = tags.strip_tags(text)
    spaced = len(_WORD_RE.findall(plain))
    cjk = len(_CJK_RE.findall(plain))
    return spaced + cjk
